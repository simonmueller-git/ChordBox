#!/usr/bin/env python3
"""
gen_data.py — generate the firmware's data headers from the ChordBox v5 sources.

  progs.txt      -> firmware/progs_data.h   (progressions + banks)
  code.py        -> firmware/chords_data.h  (CHORDS, SUBS, generator templates)
  basslines.txt  -> firmware/bass_data.h    (hand-written basslines by genre)

code.py is parsed with `ast` (never executed), so the Pico firmware stays the
single source of truth for the chord vocabulary. Run after editing either file:

    python3 tools/gen_data.py
"""

import ast
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent                      # ChordBox/
SKETCH = PROJECT / "firmware"
PICO_SRC = PROJECT / "pico"                # the Pico firmware: chord vocabulary + progressions

# full names for the OLED-era abbreviations in progs.txt
BANK_NAMES = {
    "Romant": "Romantic", "Nostlg": "Nostalgic", "Triumf": "Triumphant",
    "Surpr": "Surprised", "Myst": "Mysterious", "Cadenc": "Cadence",
    "Play": "Playful", "Rebel": "Rebellious",
}


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def literal(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in code.py")


BASS_ROLES = set("ROL5372 46bauc")
BASS_MODS = set("!'~>=+-")


def check_bass_token(tok: str, where: str) -> None:
    if tok in (".", "_"):
        return
    if tok[0] not in BASS_ROLES or tok[0] == " ":
        raise SystemExit(f"{where}: bad note {tok!r}")
    for ch in tok[1:]:
        if ch not in BASS_MODS:
            raise SystemExit(f"{where}: bad modifier {ch!r} in {tok!r}")


def gen_bass() -> str:
    genres, pats = [], []
    for n, line in enumerate((PROJECT / "basslines.txt").read_text().splitlines(), 1):
        line = line.rstrip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if parts[0] == "G":
            _, gid, name, swing, gate = parts
            genres.append([gid, name, int(swing), int(gate), len(pats), 0])
        elif parts[0] == "P":
            _, name, steps = parts
            if len(name) > 8:
                raise SystemExit(f"basslines.txt:{n}: name {name!r} longer than 8")
            toks = [t for t in steps.split() if t != "|"]
            if len(toks) not in (16, 32, 64):
                raise SystemExit(f"basslines.txt:{n}: {name} has {len(toks)} steps (want 16/32/64)")
            if toks[0] == "_":
                raise SystemExit(f"basslines.txt:{n}: {name} starts with a tie")
            for t in toks:
                check_bass_token(t, f"basslines.txt:{n} {name}")
            pats.append((name, " ".join(toks)))
            genres[-1][5] += 1
        else:
            raise SystemExit(f"basslines.txt:{n}: unknown line")
    out = ["// generated by tools/gen_data.py from basslines.txt — do not edit",
           "#pragma once", "#include <stdint.h>", "",
           "struct BassPatSrc { const char* name; const char* steps; };",
           f"static const uint16_t N_BASS_PAT = {len(pats)};",
           "static const BassPatSrc BASS_PAT[N_BASS_PAT] = {"]
    out += [f"  {{{c_str(nm)}, {c_str(st)}}}," for nm, st in pats]
    out.append("};")
    out.append("struct BassGenreSrc { const char* id; const char* name; uint8_t swing, gate; uint16_t first, count; };")
    out.append(f"static const uint8_t N_BASS_GENRE = {len(genres)};")
    out.append("static const BassGenreSrc BASS_GENRE[N_BASS_GENRE] = {")
    out += [f"  {{{c_str(g[0])}, {c_str(g[1])}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}}," for g in genres]
    out.append("};")
    (SKETCH / "bass_data.h").write_text("\n".join(out) + "\n")
    return f"{len(pats)} basslines in {len(genres)} genres"


def main() -> None:
    tree = ast.parse((PICO_SRC / "code.py").read_text())
    chords = literal(tree, "CHORDS")
    subs = literal(tree, "SUBS")
    templ_min = literal(tree, "TEMPL_MIN")
    templ_maj = literal(tree, "TEMPL_MAJ")

    progs, banks = [], []
    for line in (PICO_SRC / "progs.txt").read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        kind, a, b = line.split("\t")
        if kind == "P":
            progs.append((a, b))
        elif kind == "B":
            banks.append((a, [int(x) for x in b.split(",")]))

    unknown = sorted({t for _, toks in progs for t in toks.split()} - set(chords))
    if unknown:
        raise SystemExit(f"tokens missing from CHORDS: {unknown}")
    for bank, rows in banks:
        for r in rows:
            if r >> 1 >= len(progs):
                raise SystemExit(f"bank {bank}: row {r} points past the progs list")

    names = list(chords)
    idx = {n: i for i, n in enumerate(names)}
    if len(names) > 250:
        raise SystemExit("too many chord types for uint8_t ids")

    # ---- chords_data.h ----------------------------------------------------
    out = ["// generated by tools/gen_data.py from code.py — do not edit",
           "#pragma once", "#include <stdint.h>", "",
           "struct ChordDef { const char* name; int8_t iv[6]; uint8_t n; };",
           f"static const uint8_t N_CHORDS = {len(names)};",
           "static const ChordDef CHORD_DEFS[N_CHORDS] = {"]
    for n in names:
        iv = list(chords[n])
        out.append(f"  {{{c_str(n)}, {{{', '.join(str(x) for x in iv + [0] * (6 - len(iv)))}}}, {len(iv)}}},")
    out.append("};")
    out.append("")
    out.append("// substitution pools, by chord id (0xFF = none)")
    out.append("struct SubDef { uint8_t from; uint8_t to[4]; uint8_t n; };")
    out.append(f"static const uint8_t N_SUBS = {len(subs)};")
    out.append("static const SubDef SUB_DEFS[N_SUBS] = {")
    for k, pool in subs.items():
        ids = [idx[p] for p in pool]
        out.append(f"  {{{idx[k]}, {{{', '.join(str(x) for x in ids + [255] * (4 - len(ids)))}}}, {len(ids)}}},  // {k}")
    out.append("};")
    for label, templ in (("TEMPL_MIN", templ_min), ("TEMPL_MAJ", templ_maj)):
        out.append(f"static const uint8_t N_{label} = {len(templ)};")
        out.append(f"static const uint8_t {label}[N_{label}][4] = {{")
        for t in templ:
            out.append("  {" + ", ".join(str(idx[x]) for x in t) + "},  // " + " ".join(t))
        out.append("};")
    (SKETCH / "chords_data.h").write_text("\n".join(out) + "\n")

    # ---- progs_data.h -----------------------------------------------------
    out = ["// generated by tools/gen_data.py from progs.txt — do not edit",
           "// progressions derived from free-midi-chords (c) 2019 Ludovic Drolez, MIT",
           "#pragma once", "#include <stdint.h>", "",
           "struct ProgSrc { const char* name; const char* toks; };",
           f"static const uint16_t N_PROG_SRC = {len(progs)};",
           "static const ProgSrc PROG_SRC[N_PROG_SRC] = {"]
    for name, toks in progs:
        out.append(f"  {{{c_str(name)}, {c_str(toks)}}},")
    out.append("};")
    for i, (_, rows) in enumerate(banks):
        out.append(f"static const uint16_t BANK_ROWS_{i}[] = {{{', '.join(map(str, rows))}}};")
    out.append("struct BankSrc { const char* name; const uint16_t* rows; uint16_t n; };")
    out.append(f"static const uint8_t N_BANK_SRC = {len(banks)};")
    out.append("static const BankSrc BANK_SRC[N_BANK_SRC] = {")
    for i, (name, rows) in enumerate(banks):
        out.append(f"  {{{c_str(BANK_NAMES.get(name, name))}, BANK_ROWS_{i}, {len(rows)}}},")
    out.append("};")
    (SKETCH / "progs_data.h").write_text("\n".join(out) + "\n")

    print(gen_bass())
    print(f"{len(names)} chord types, {len(subs)} sub pools, "
          f"{len(templ_min)}+{len(templ_maj)} templates, "
          f"{len(progs)} progressions, {len(banks)} banks")


if __name__ == "__main__":
    sys.exit(main())
